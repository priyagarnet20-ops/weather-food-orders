"""
Synthetic Food-Delivery Order Generator — Weather-Driven Patterns (Coimbatore)
================================================================================

INPUT
-----
weather_clean.csv : one row per day, 2025-09-24 to 2026-09-24, pulled from the
Open-Meteo Historical Weather API for Coimbatore (11.00N, 76.99E). Columns:
date, precip_mm, rain_mm, temp_max_c, temp_min_c, wind_max_kmh, weather_code,
temp_mean_c, daylight_s.

This is REAL data. Everything below it (order counts, baskets, items) is
SYNTHETIC, generated by the rules documented in this file. No external order
data of any kind is used.

WHY SYNTHETIC ORDERS ARE GENERATED THIS WAY
--------------------------------------------
The goal is a dataset where weather has a *known, documented* causal effect,
so that downstream methods (regression, time-series forecasting, association
rule mining) have real signal to recover — and so the results can be checked
against the generation rules for correctness, not just plausibility.

STEP 1 — Daily order volume
----------------------------
Each day gets a baseline order count that depends on:
  - Day of week: Fri/Sat/Sun get a weekend bump (delivery apps see more
    weekend ordering).
  - Rain: comfort-food delivery demand rises when people don't want to go
    out. The bump scales with rain intensity, not just yes/no rain.
  - Heat: on very hot days people avoid cooking and order more too, but the
    effect is smaller than rain's.
  - Random noise: Negative binomial noise so variance looks like real demand
    data, not a deterministic curve.

    base_weekday      = 140
    weekend_multiplier = 1.30                  (Fri, Sat, Sun)
    rain_multiplier:
        precip < 2.5mm   -> 1.00               (dry / trace)
        2.5 <= p < 15mm  -> 1.20               (moderate rain)
        p >= 15mm        -> 1.35               (heavy rain)
    heat_multiplier:
        temp_max >= 33C  -> 1.10
        else             -> 1.00
    expected_orders = base_weekday * weekend_multiplier * rain_multiplier * heat_multiplier
    actual_orders   ~ NegativeBinomial(mean=expected_orders, dispersion r=25)

STEP 2 — Weather regime label (used for both order generation and later ARM)
------------------------------------------------------------------------------
    is_rainy = precip_mm >= 2.5          (meaningful rain, not trace drizzle)
    is_hot   = temp_max_c >= 33.0         (roughly top quartile for this data)
    regime   = "rainy" if is_rainy else ("hot" if is_hot else "normal")

STEP 3 — Menu and category weather-affinity
---------------------------------------------
20 menu items across 3 categories. Each category has a base popularity share
and a weather multiplier applied to that share before basket sampling:

    Category         Items                                         Rainy  Hot   Normal
    ---------------- --------------------------------------------- ------ ----- -------
    hot_comfort      Chai, Coffee, Pakora, Samosa, Vada, Bajji,      1.8x  0.8x   1.0x
                      Soup
    cold_refresh     Ice Cream, Cold Coffee, Buttermilk,             0.6x  1.9x   1.0x
                      Fresh Lime Juice, Fruit Salad
    mains            Dosa, Idli, Biryani, Fried Rice, Noodles,       1.0x  1.0x   1.0x
                      Pizza, Burger, Sandwich

Within a category, items have fixed relative base weights (see ITEM_WEIGHTS).

STEP 4 — Basket construction (this is what creates the association rules)
-----------------------------------------------------------------------------
Basket size k ~ {1: 0.35, 2: 0.40, 3: 0.18, 4: 0.07}

  1. Sample the first item from the weather-adjusted item distribution.
  2. For each additional slot, first check the PAIR_RULES table for a
     conditional "add-on" triggered by an item already in the basket. If
     triggered, add that paired item directly (this is what creates
     strong, weather-dependent lift). Otherwise sample the next item from
     the weather-adjusted distribution, avoiding duplicates.

  Documented pair rules (probability an add-on is appended given the
  trigger item is already in the basket):

    Trigger    Add-on         Rainy-day prob   Dry/Normal-day prob
    ---------- -------------- ---------------- ---------------------
    Chai       Pakora         0.55             0.12
    Chai       Samosa         0.30             0.10
    Coffee     Vada           0.25             0.10
    Biryani    Buttermilk     0.15 (rainy)     0.35 (hot) / 0.15 (normal)
    Ice Cream  Cold Coffee    0.10 (rainy)     0.30 (hot) / 0.12 (normal)

  These rules are deliberately weather-conditioned: {Chai} -> {Pakora} is
  the headline example in the brief, and its confidence/lift should come
  out clearly higher on rainy days than dry days once you run Apriori/
  FP-Growth separately on each subset — because that's exactly how it was
  generated.

REPRODUCIBILITY
----------------
A fixed numpy random seed (SEED) is used throughout, so re-running this
script regenerates an identical dataset. Change SEED to get a different
draw for sensitivity checks.

OUTPUTS
-------
  daily_orders.csv     : date, weather features, regime flags, order_count
                          -> feed this to the Review-1 regression model and
                             the Review-2 time-series forecast.
  order_items.csv      : order_id, date, item                (long/basket format)
                          -> feed this to Apriori / FP-Growth for the ARM task.
"""

import numpy as np
import pandas as pd

SEED = 42
rng = np.random.default_rng(SEED)

# ---------------------------------------------------------------------------
# Load real weather data
# ---------------------------------------------------------------------------
weather = pd.read_csv("weather_clean.csv", parse_dates=["date"])
weather = weather.sort_values("date").reset_index(drop=True)

weather["is_rainy"] = weather["precip_mm"] >= 2.5
weather["is_hot"] = weather["temp_max_c"] >= 33.0
weather["regime"] = np.select(
    [weather["is_rainy"], weather["is_hot"]],
    ["rainy", "hot"],
    default="normal",
)
weather["is_weekend"] = weather["date"].dt.dayofweek.isin([4, 5, 6])  # Fri/Sat/Sun

# ---------------------------------------------------------------------------
# STEP 1: daily order volume
# ---------------------------------------------------------------------------
BASE_WEEKDAY = 140
WEEKEND_MULT = 1.30
NB_DISPERSION = 25  # negative binomial 'r' parameter -> controls variance


def rain_multiplier(precip_mm: float) -> float:
    if precip_mm >= 15:
        return 1.35
    elif precip_mm >= 2.5:
        return 1.20
    return 1.00


def heat_multiplier(temp_max_c: float) -> float:
    return 1.10 if temp_max_c >= 33.0 else 1.00


expected = (
    BASE_WEEKDAY
    * weather["is_weekend"].map({True: WEEKEND_MULT, False: 1.0})
    * weather["precip_mm"].apply(rain_multiplier)
    * weather["temp_max_c"].apply(heat_multiplier)
)

# Negative binomial via gamma-poisson mixture for realistic overdispersion
p_nb = NB_DISPERSION / (NB_DISPERSION + expected)
order_count = rng.negative_binomial(NB_DISPERSION, p_nb)

weather["order_count"] = order_count
weather.to_csv("daily_orders.csv", index=False)

# ---------------------------------------------------------------------------
# STEP 3: menu + category weather-affinity
# ---------------------------------------------------------------------------
CATEGORY_ITEMS = {
    "hot_comfort": ["Chai", "Coffee", "Pakora", "Samosa", "Vada", "Bajji", "Soup"],
    "cold_refresh": ["Ice Cream", "Cold Coffee", "Buttermilk", "Fresh Lime Juice", "Fruit Salad"],
    "mains": ["Dosa", "Idli", "Biryani", "Fried Rice", "Noodles", "Pizza", "Burger", "Sandwich"],
}

CATEGORY_WEATHER_MULT = {
    "hot_comfort": {"rainy": 1.8, "hot": 0.8, "normal": 1.0},
    "cold_refresh": {"rainy": 0.6, "hot": 1.9, "normal": 1.0},
    "mains": {"rainy": 1.0, "hot": 1.0, "normal": 1.0},
}

# fixed relative base weight of each item within its category
ITEM_WEIGHTS = {
    "Chai": 3.0, "Coffee": 2.0, "Pakora": 1.5, "Samosa": 1.5, "Vada": 1.2, "Bajji": 1.0, "Soup": 0.8,
    "Ice Cream": 1.8, "Cold Coffee": 1.6, "Buttermilk": 1.2, "Fresh Lime Juice": 1.4, "Fruit Salad": 0.8,
    "Dosa": 2.2, "Idli": 1.8, "Biryani": 2.5, "Fried Rice": 1.6, "Noodles": 1.4, "Pizza": 1.6,
    "Burger": 1.5, "Sandwich": 1.2,
}

ITEM_TO_CATEGORY = {item: cat for cat, items in CATEGORY_ITEMS.items() for item in items}
ALL_ITEMS = list(ITEM_WEIGHTS.keys())


def item_distribution(regime: str) -> np.ndarray:
    weights = np.array(
        [ITEM_WEIGHTS[i] * CATEGORY_WEATHER_MULT[ITEM_TO_CATEGORY[i]][regime] for i in ALL_ITEMS]
    )
    return weights / weights.sum()


REGIME_DISTS = {r: item_distribution(r) for r in ["rainy", "hot", "normal"]}

# ---------------------------------------------------------------------------
# STEP 4: pair (co-occurrence) rules
# ---------------------------------------------------------------------------
# trigger -> add_on -> {regime: probability}
PAIR_RULES = {
    "Chai": {
        "Pakora": {"rainy": 0.55, "hot": 0.12, "normal": 0.12},
        "Samosa": {"rainy": 0.30, "hot": 0.10, "normal": 0.10},
    },
    "Coffee": {
        "Vada": {"rainy": 0.25, "hot": 0.10, "normal": 0.10},
    },
    "Biryani": {
        "Buttermilk": {"rainy": 0.15, "hot": 0.35, "normal": 0.15},
    },
    "Ice Cream": {
        "Cold Coffee": {"rainy": 0.10, "hot": 0.30, "normal": 0.12},
    },
}

BASKET_SIZE_PROBS = {1: 0.35, 2: 0.40, 3: 0.18, 4: 0.07}
basket_sizes = np.array(list(BASKET_SIZE_PROBS.keys()))
basket_probs = np.array(list(BASKET_SIZE_PROBS.values()))


def sample_item(regime: str, exclude: set) -> str:
    dist = REGIME_DISTS[regime].copy()
    if exclude:
        idx = [ALL_ITEMS.index(i) for i in exclude]
        dist[idx] = 0
        if dist.sum() == 0:
            return None
        dist = dist / dist.sum()
    return rng.choice(ALL_ITEMS, p=dist)


def build_basket(regime: str) -> list:
    k = rng.choice(basket_sizes, p=basket_probs)
    basket = [sample_item(regime, exclude=set())]
    while len(basket) < k:
        added_via_rule = False
        # check pair rules for any item already in basket
        for trigger in basket:
            if trigger in PAIR_RULES:
                for add_on, probs in PAIR_RULES[trigger].items():
                    if add_on not in basket and rng.random() < probs[regime]:
                        basket.append(add_on)
                        added_via_rule = True
                        break
            if added_via_rule:
                break
        if added_via_rule:
            continue
        nxt = sample_item(regime, exclude=set(basket))
        if nxt is None:
            break
        basket.append(nxt)
    return basket


# ---------------------------------------------------------------------------
# Generate all orders
# ---------------------------------------------------------------------------
rows = []
order_id = 1
for _, day in weather.iterrows():
    for _ in range(int(day["order_count"])):
        basket = build_basket(day["regime"])
        for item in basket:
            rows.append({"order_id": order_id, "date": day["date"], "item": item})
        order_id += 1

order_items = pd.DataFrame(rows)
order_items.to_csv("order_items.csv", index=False)

# ---------------------------------------------------------------------------
# Sanity check: does the {Chai} -> {Pakora} lift actually differ by regime?
# ---------------------------------------------------------------------------
def basket_lift(df_items: pd.DataFrame, a: str, b: str) -> float:
    orders = df_items.groupby("order_id")["item"].apply(set)
    n = len(orders)
    supp_a = orders.apply(lambda s: a in s).mean()
    supp_b = orders.apply(lambda s: b in s).mean()
    supp_ab = orders.apply(lambda s: a in s and b in s).mean()
    if supp_a == 0 or supp_b == 0 or supp_ab == 0:
        return float("nan")
    return supp_ab / (supp_a * supp_b)


merged = order_items.merge(weather[["date", "regime"]], on="date")
for regime in ["rainy", "hot", "normal"]:
    sub = merged[merged["regime"] == regime]
    lift = basket_lift(sub, "Chai", "Pakora")
    print(f"regime={regime:7s}  n_orders={sub['order_id'].nunique():5d}  lift(Chai->Pakora)={lift:.2f}")

print("\nGenerated:")
print(f"  daily_orders.csv : {len(weather)} days")
print(f"  order_items.csv  : {order_items['order_id'].nunique()} orders, {len(order_items)} line items")
